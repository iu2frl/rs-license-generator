// Bit-permutes value: each set bit x of value is moved to output position table[(nibble<<5)+x]
function fspCipher(nibble, value, table) {
    let result = 0;
    for (let x = 0; x < 32; x++) {
        if (value & (1 << x)) {
            result |= 1 << table[(nibble << 5) + x];
        }
    }
    return result >>> 0;
}

// "NNNNNN/XXX" -> NNNNNN * 1000 + XXX, matching the original strtoul-based parsing
function fspSerialToInt(serial) {
    const parts = serial.split('/');
    let seriale = parseInt(parts[0], 10) * 1000;
    if (parts.length > 1) seriale += parseInt(parts[1], 10);
    return seriale >>> 0;
}

