class FspGenerator extends InstrumentGenerator {
    constructor() {
        super('fsp', 'FSP series');
    }

    getOptions() {
        return FSP_OPTIONS;
    }

    validateSerial(serial) {
        const parts = serial.split('/');
        if (parts.some(p => !Number.isFinite(parseInt(p, 10)))) {
            return { valid: false, message: 'Invalid serial format. Use NNNNNN/XXX' };
        }
        return { valid: true };
    }

    generateKey(serial, option) {
        const seriale = fspSerialToInt(serial);
        let value = option.code >>> 0;
        for (let x = 0; x < 8; x++) {
            const shift = (seriale >>> (4 * (7 - x))) & 0xF;
            value = (fspCipher(shift, value, FSP_ENCRYPT_TABLE) + FSP_TAVOLA_ADD[shift]) >>> 0;
        }
        return value;
    }

    formatKey(rawKey) {
        return String(rawKey >>> 0).padStart(10, '0');
    }
}
